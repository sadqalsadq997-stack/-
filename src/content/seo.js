function faqLd(faqs) {
  return { '@type': 'FAQPage', mainEntity: faqs.map(f => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })) };
}
function crumbs(items) {
  return { '@type': 'BreadcrumbList', itemListElement: items.map((it, i) => ({ '@type': 'ListItem', position: i + 1, name: it.name, item: `${SITE.url}${it.path}` })) };
}

export function getHead(path) {
  const clean = path.replace(/\/+$/, '') || '/';
  const sol = SOLUTIONS.find(s => `/${s.slug}` === clean);
  const base = sol ? { title: sol.title, description: sol.description, keywords: sol.keywords } : STATIC_PAGES[clean];
  if (!base) return null;
  const canonical = clean === '/' ? `${SITE.url}/` : `${SITE.url}${clean}`;
  const graph = [org];
  if (clean === '/') {
    graph.push({ '@type': 'WebSite', '@id': `${SITE.url}/#website`, url: `${SITE.url}/`, name: 'فلسي Felsy', inLanguage: 'ar', publisher: { '@id': `${SITE.url}/#org` } });
    graph.push(software, faqLd(HOME_FAQS));
  } else if (clean === '/pricing') {
    graph.push(software, faqLd(PRICING_FAQS), crumbs([{ name: 'الرئيسية', path: '/' }, { name: 'الأسعار', path: '/pricing' }]));
  } else if (sol) {
    graph.push({
      '@type': 'WebPage', '@id': `${canonical}#page`, url: canonical, name: sol.h1, description: sol.description,
      inLanguage: 'ar', about: { '@id': `${SITE.url}/#software` }, dateModified: SITE.updated,
    });
    graph.push(software, faqLd(sol.faqs), crumbs([{ name: 'الرئيسية', path: '/' }, { name: sol.nav, path: clean }]));
  } else {
    graph.push(crumbs([{ name: 'الرئيسية', path: '/' }, { name: base.title.split(' — ')[0], path: clean }]));
  }
  return { ...base, canonical, jsonLd: { '@context': 'https://schema.org', '@graph': graph } };
}
